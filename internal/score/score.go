// Package score measures detections against simulator ground truth.
//
// Scoring is per session (one QUIC connection), because that is what
// network sensors log. For each detector, a session counts as detected if
// at least one of the detector's alerts matches it: same endpoints in
// either direction, and a timestamp inside the session's lifetime (plus a
// tolerance for clock and capture skew).
package score

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/netip"
	"sort"
	"strconv"
	"strings"
	"text/tabwriter"
	"time"

	"github.com/1337-llama/quic_research/internal/detect"
	"github.com/1337-llama/quic_research/internal/eve"
	"github.com/1337-llama/quic_research/internal/groundtruth"
	"github.com/1337-llama/quic_research/internal/profile"
	"github.com/1337-llama/quic_research/internal/zeeklog"
)

// AnyDetector is the pseudo-detector that combines every alert.
const AnyDetector = "(any)"

// DefaultTolerance is the default timestamp slack when matching.
const DefaultTolerance = 5 * time.Second

// Alert is a detector-neutral alert.
type Alert struct {
	Detector string
	TS       time.Time
	A, B     netip.AddrPort
}

// FromDetect converts reference-detector alerts.
func FromDetect(in []detect.Alert) []Alert {
	out := make([]Alert, len(in))
	for i, a := range in {
		out[i] = Alert{Detector: a.Detector, TS: a.TS, A: a.Orig, B: a.Resp}
	}
	return out
}

// FromEVE converts Suricata alerts. Detectors are named "suricata:<signature>".
func FromEVE(in []eve.Alert) []Alert {
	out := make([]Alert, len(in))
	for i, a := range in {
		out[i] = Alert{Detector: "suricata:" + a.Signature, TS: a.TS, A: a.Src, B: a.Dst}
	}
	return out
}

// FromNotices converts Zeek notices. Detectors are named "zeek:<note>".
// Notices without endpoints cannot be matched and are still counted as
// unmatched alerts.
func FromNotices(in []zeeklog.Notice) []Alert {
	out := make([]Alert, len(in))
	for i, n := range in {
		out[i] = Alert{Detector: "zeek:" + n.Note, TS: n.TS, A: n.Orig, B: n.Resp}
	}
	return out
}

// Options tunes matching.
type Options struct {
	// Tolerance widens each session's time window on both sides.
	Tolerance time.Duration
}

// Result is one detector's score.
type Result struct {
	Detector string `json:"detector"`
	Alerts   int    `json:"alerts"`
	// TP: malicious sessions detected. FP: benign sessions detected.
	// FN: malicious sessions missed. TN: benign sessions not detected.
	TP int `json:"tp"`
	FP int `json:"fp"`
	FN int `json:"fn"`
	TN int `json:"tn"`
	// Unmatched counts alerts that matched no session at all, e.g. traffic
	// that was not generated by the simulator.
	Unmatched int `json:"unmatched"`
	// Precision, Recall and F1 are 0 when undefined (no positives).
	Precision float64 `json:"precision"`
	Recall    float64 `json:"recall"`
	F1        float64 `json:"f1"`
}

// Report is a complete scoring run.
type Report struct {
	Sessions  int      `json:"sessions"`
	Malicious int      `json:"malicious"`
	Benign    int      `json:"benign"`
	Results   []Result `json:"results"`
}

// Result returns the named detector's result.
func (r Report) Result(detector string) (Result, bool) {
	for _, res := range r.Results {
		if res.Detector == detector {
			return res, true
		}
	}
	return Result{}, false
}

// Score evaluates alerts against session ground truth. Results are sorted
// by detector name, with AnyDetector first.
func Score(sessions []groundtruth.Record, alerts []Alert, opt Options) (Report, error) {
	if opt.Tolerance < 0 {
		return Report{}, errors.New("score: tolerance must not be negative")
	}
	rep := Report{Sessions: len(sessions)}
	for _, s := range sessions {
		if s.Kind != groundtruth.KindSession {
			return Report{}, fmt.Errorf("score: record for run %q session %d is a %q, not a session", s.RunID, s.SessionID, s.Kind)
		}
		if s.Label == profile.LabelMalicious {
			rep.Malicious++
		} else {
			rep.Benign++
		}
	}

	// Match every alert once, then derive per-detector results.
	byDetector := map[string][]int{AnyDetector: nil} // detector -> matched session indices (with repeats)
	counts := map[string]*Result{AnyDetector: {Detector: AnyDetector}}
	for _, a := range alerts {
		res, ok := counts[a.Detector]
		if !ok {
			res = &Result{Detector: a.Detector}
			counts[a.Detector] = res
		}
		res.Alerts++
		counts[AnyDetector].Alerts++
		matched := false
		for i, s := range sessions {
			if matches(s, a, opt.Tolerance) {
				matched = true
				byDetector[a.Detector] = append(byDetector[a.Detector], i)
				byDetector[AnyDetector] = append(byDetector[AnyDetector], i)
			}
		}
		if !matched {
			res.Unmatched++
			counts[AnyDetector].Unmatched++
		}
	}

	for det, res := range counts {
		hit := make(map[int]bool)
		for _, i := range byDetector[det] {
			hit[i] = true
		}
		for i, s := range sessions {
			switch {
			case s.Label == profile.LabelMalicious && hit[i]:
				res.TP++
			case s.Label == profile.LabelMalicious:
				res.FN++
			case hit[i]:
				res.FP++
			default:
				res.TN++
			}
		}
		res.Precision = ratio(res.TP, res.TP+res.FP)
		res.Recall = ratio(res.TP, res.TP+res.FN)
		if res.Precision+res.Recall > 0 {
			res.F1 = 2 * res.Precision * res.Recall / (res.Precision + res.Recall)
		}
		rep.Results = append(rep.Results, *res)
	}
	sort.Slice(rep.Results, func(i, j int) bool {
		a, b := rep.Results[i].Detector, rep.Results[j].Detector
		if (a == AnyDetector) != (b == AnyDetector) {
			return a == AnyDetector
		}
		return a < b
	})
	return rep, nil
}

func ratio(n, d int) float64 {
	if d == 0 {
		return 0
	}
	return float64(n) / float64(d)
}

func matches(s groundtruth.Record, a Alert, tol time.Duration) bool {
	if a.TS.Before(s.Start.Add(-tol)) || a.TS.After(s.End.Add(tol)) {
		return false
	}
	return (endpointMatch(s.Local, a.A) && endpointMatch(s.Remote, a.B)) ||
		(endpointMatch(s.Local, a.B) && endpointMatch(s.Remote, a.A))
}

// endpointMatch compares a ground-truth endpoint with an observed one. An
// unspecified ground-truth address (a socket bound to 0.0.0.0) matches any
// address, but ports must always agree.
func endpointMatch(truth, seen netip.AddrPort) bool {
	if !truth.IsValid() || !seen.IsValid() || truth.Port() != seen.Port() {
		return false
	}
	ta := truth.Addr().Unmap()
	return ta.IsUnspecified() || ta == seen.Addr().Unmap()
}

// WriteText writes the report as an aligned table.
func WriteText(w io.Writer, r Report) error {
	if _, err := fmt.Fprintf(w, "sessions: %d (malicious %d, benign %d)\n\n", r.Sessions, r.Malicious, r.Benign); err != nil {
		return err
	}
	tw := tabwriter.NewWriter(w, 0, 0, 2, ' ', tabwriter.AlignRight|tabwriter.Debug)
	fmt.Fprintln(tw, "detector\talerts\tTP\tFP\tFN\tTN\tunmatched\tprecision\trecall\tF1\t")
	for _, res := range r.Results {
		fmt.Fprintf(tw, "%s\t%d\t%d\t%d\t%d\t%d\t%d\t%.3f\t%.3f\t%.3f\t\n",
			res.Detector, res.Alerts, res.TP, res.FP, res.FN, res.TN, res.Unmatched, res.Precision, res.Recall, res.F1)
	}
	return tw.Flush()
}

// WriteJSON writes the report as indented JSON.
func WriteJSON(w io.Writer, r Report) error {
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	return enc.Encode(r)
}

// Requirement is a minimum score for one detector, used as a CI gate.
type Requirement struct {
	Detector string
	Metric   string
	Min      float64
}

// ParseRequirement parses "detector:metric>=value", e.g.
// "(any):recall>=0.95" or "zeek:QUICHunt::Long_QUIC_Connection:precision>=1".
// The detector name may itself contain colons; the metric is the text
// between the last colon and ">=".
func ParseRequirement(s string) (Requirement, error) {
	lhs, val, ok := strings.Cut(s, ">=")
	if !ok {
		return Requirement{}, fmt.Errorf("requirement %q: want detector:metric>=value", s)
	}
	i := strings.LastIndex(lhs, ":")
	if i <= 0 || i == len(lhs)-1 {
		return Requirement{}, fmt.Errorf("requirement %q: want detector:metric>=value", s)
	}
	req := Requirement{Detector: lhs[:i], Metric: lhs[i+1:]}
	switch req.Metric {
	case "precision", "recall", "f1":
	default:
		return Requirement{}, fmt.Errorf("requirement %q: metric must be precision, recall or f1", s)
	}
	f, err := strconv.ParseFloat(strings.TrimSpace(val), 64)
	if err != nil || f < 0 || f > 1 {
		return Requirement{}, fmt.Errorf("requirement %q: value must be a number in [0, 1]", s)
	}
	req.Min = f
	return req, nil
}

// String formats the requirement in the syntax ParseRequirement accepts.
func (q Requirement) String() string {
	return fmt.Sprintf("%s:%s>=%g", q.Detector, q.Metric, q.Min)
}

// Check returns one error per unmet requirement. A requirement on a
// detector that produced no alerts fails.
func Check(r Report, reqs []Requirement) []error {
	var errs []error
	for _, q := range reqs {
		res, ok := r.Result(q.Detector)
		if !ok {
			errs = append(errs, fmt.Errorf("%s: detector %q produced no alerts", q, q.Detector))
			continue
		}
		var got float64
		switch q.Metric {
		case "precision":
			got = res.Precision
		case "recall":
			got = res.Recall
		default:
			got = res.F1
		}
		if got < q.Min {
			errs = append(errs, fmt.Errorf("%s: got %.3f", q, got))
		}
	}
	return errs
}
